export const DICTS: Record<Lang, Dict> = { pt, en, es }
export const LANGS: Lang[] = ['pt', 'en', 'es']
const HTML_LANG: Record<Lang, string> = { pt: 'pt-BR', en: 'en', es: 'es' }
const STORAGE_KEY = 'carol-alves-lang'

type Ctx = { lang: Lang; t: Dict; setLang: (l: Lang) => void }
const LangContext = createContext<Ctx>({ lang: 'pt', t: pt, setLang: () => {} })

export function LanguageProvider({ children }: { children: ReactNode }) {
  // Sempre 'pt' no servidor e no primeiro render; preferência salva aplicada após montar.
  const [lang, setLangState] = useState<Lang>('pt')

  useEffect(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY)
    if (saved === 'en' || saved === 'es' || saved === 'pt') setLangState(saved)
  }, [])

  useEffect(() => {
    document.documentElement.lang = HTML_LANG[lang]
  }, [lang])

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    window.localStorage.setItem(STORAGE_KEY, l)
  }, [])

  return <LangContext.Provider value={{ lang, t: DICTS[lang], setLang }}>{children}</LangContext.Provider>
}

export function useLang() {
  return useContext(LangContext)
}
